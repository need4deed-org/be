function isStringRecord(value: unknown): value is Record<string, string> {
  return (
    typeof value === "object" &&
    value !== null &&
    !Array.isArray(value) &&
    Object.values(value).every((v) => typeof v === "string" && v.trim() !== "")
  );
}

export async function loadOrganizationTitleMap(
  url = ORGANIZATION_TITLES_URL,
): Promise<OrganizationTitleMap> {
  const builtin = {
    titles: BUILTIN_ORGANIZATION_TITLES,
    aliases: BUILTIN_ORGANIZATION_ALIASES,
  };
  try {
    const res = await fetch(url, {
      signal: AbortSignal.timeout(FETCH_TIMEOUT_MS),
    });
    if (!res.ok) {
      throw new Error(`HTTP ${res.status}`);
    }
    const body = (await res.json()) as Partial<OrganizationTitleMap>;
    const titles = body?.titles ?? {};
    const aliases = body?.aliases ?? {};
    if (!isStringRecord(titles) || !isStringRecord(aliases)) {
      throw new Error("expected { titles, aliases } of string -> string");
    }
    console.warn(
      `[rename-domain-seeded-organizations] using CDN map (${Object.keys(titles).length} title and ${Object.keys(aliases).length} alias override(s)) over the built-in one`,
    );
    return {
      titles: { ...builtin.titles, ...titles },
      aliases: { ...builtin.aliases, ...aliases },
    };
  } catch (err) {
    console.warn(
      `[rename-domain-seeded-organizations] CDN map unavailable (${url}: ${err instanceof Error ? err.message : err}), using the built-in one`,
    );
    return builtin;
  }
}
